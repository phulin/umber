# Derives the per-channel contract for every declarative minifixture against
# the pinned instrumented pdfTeX 1.40.27 oracle.
#
# This runs the same `tex_command_stream::semantic` code the gate runs, so a
# regenerated contract cannot describe a run the gate would not reproduce.
# Every committed channel file holds the reference engine's bytes, for `file`
# and `xfail` alike (`umber2-alfh.7`); this tool decides only the disposition
# by comparing Umber's own run against that capture. It therefore needs
# `scripts/run-minifixture-oracle.sh --all` to have already populated
# `target/minifixture-oracle` (which in turn needs
# `scripts/build-pdftex14027-oracle.sh` and `UMBER_REF_TEXLIVE_SOURCE`) --
# this function does not run either script itself, and fails loudly, listing
# every affected case, rather than silently regenerating against a missing or
# stale capture.
regen_command_semantic_area() {
  local profile="${1:-}"
  local allowlist="${2:-}"
  [[ -n "$profile" && -n "$allowlist" ]] ||
    die 'command-semantic regeneration requires --profile PROFILE --allowlist FILE'
  [[ "$profile" == raw-tex82-loaded ]] ||
    die "unsupported command-semantic oracle profile: ${profile}"
  [[ -f "$allowlist" ]] || die "command-semantic allowlist does not exist: ${allowlist}"
  [[ -x "$command_semantic_channels_bin" ]] ||
    die "command-semantic regeneration tool is not built: ${command_semantic_channels_bin}; run cargo build -p tex-command-stream first"
  run_command "Capturing ${profile} command-semantic oracle channels" \
    "${repo_root}/scripts/run-minifixture-oracle.sh" \
    --profile "$profile" --allowlist "$allowlist"
  run_command 'Deriving command-semantic channel contracts against the pinned oracle' \
    "$command_semantic_channels_bin" --allowlist "$allowlist" \
    --accept-projection-changes
}

regen_area() {
  local area="$1"
  is_known_area "$area" || die "unknown fixture area: ${area}"
  if is_text_area "$area"; then
    regen_text_area "$area"
  elif is_dvi_area "$area"; then
    regen_dvi_area "$area"
  elif [[ "$area" == "$pdf_area" ]]; then
    regen_pdf_area
  elif [[ "$area" == "$e2e_area" ]]; then
    regen_e2e_area
  elif [[ "$area" == "$bib_area" ]]; then
    regen_bib_area
  elif [[ "$area" == "$bibtex_area" ]]; then
    regen_bibtex_area
  elif [[ "$area" == "$command_semantic_area" ]]; then
    regen_command_semantic_area "$command_semantic_profile" "$command_semantic_allowlist"
  elif [[ "$area" == "$tex82_oracle_area" || \
          "$area" == "$etex26_oracle_area" || \
          "$area" == "$pdftex14027_oracle_area" ]]; then
    die "use --oracle ENGINE --profile PROFILE for oracle regeneration"
  else
    run_fonts_live_check
  fi
}

case_area_from_arg() {
  local spec="$1"
  printf '%s\n' "${spec%%/*}"
}

case_name_from_arg() {
  local spec="$1"
  local name="${spec#*/}"
  name="${name%.tex}"
  name="${name%.expected.dvi}"
  name="${name%.expected.log}"
  name="${name%.expected.tokens}"
  name="${name%.expected.ref}"
  name="${name%.expected.out}"
  name="${name%.expected.effects}"
  name="${name%.expected.specials}"
  printf '%s\n' "$name"
}

regen_case() {
  local area="$1"
  local case="$2"
  local command_string
  is_known_area "$area" || die "unknown fixture area: ${area}"
  if is_dvi_area "$area"; then
    regen_dvi_case "$area" "$case"
    validate_dvi_area "$area"
  elif [[ "$area" == "$e2e_area" ]]; then
    regen_e2e_case "$case"
  elif [[ "$area" == "$pdf_area" ]]; then
    build_fixturegen_once
    build_umber_once
    run_command "Regenerating pdf/${case} fixtures" \
      env UMBER_BIN="$umber_bin" "$fixturegen_bin" --case pdf "$case"
    command_string="$(test_command_for_area pdf)"
    # shellcheck disable=SC2086
    run_command 'Validating hermetic PDF parity fixtures' $command_string
  elif [[ "$area" == "$bib_area" ]]; then
    die '--case is not meaningful for the pinned bibliography fixture set'
  elif [[ "$area" == "$bibtex_area" ]]; then
    [[ "$case" == "smoke" ]] || die "unknown classic BibTeX fixture case: ${case}"
    regen_bibtex_area
  elif [[ "$area" == "$tex82_oracle_area" ]]; then
    die '--case is not meaningful for the TeX82 oracle build'
  elif [[ "$area" == "$etex26_oracle_area" ]]; then
    die '--case is not meaningful for the e-TeX 2.6 oracle build'
  elif [[ "$area" == "$pdftex14027_oracle_area" ]]; then
    die '--case is not meaningful for the pdfTeX 1.40.27 oracle build'
  elif is_text_area "$area"; then
    printf 'Regenerating text area %s for requested case %s\n' "$area" "$case" >&2
    build_fixturegen_once
    if fixturegen_needs_umber "$area"; then
      build_umber_once
    fi
    run_command "Regenerating ${area}/${case} fixture" \
      env UMBER_BIN="$umber_bin" "$fixturegen_bin" --case "$area" "$case"
    command_string="$(test_command_for_area "$area")"
    # shellcheck disable=SC2086
    run_command "Validating ${area} fixtures" $command_string
  else
    die "--case is not meaningful for the fonts live check"
  fi
}

incremental_specs() {
  {
    git diff --name-only -- tests/corpus
    git diff --name-only --cached -- tests/corpus
    git ls-files --others --exclude-standard -- tests/corpus
  } | sort -u
}

regen_incremental() {
  local path
  local area
  local file
  local stem
  local case_specs_file
  local area_specs_file
  local spec

  case_specs_file="$(mktemp)"
  area_specs_file="$(mktemp)"

  while IFS= read -r path; do
    [[ -n "$path" ]] || continue
    case "$path" in
      tests/corpus/*/*)
        area="${path#tests/corpus/}"
        area="${area%%/*}"
        file="$(basename "$path")"
        if ! is_known_area "$area"; then
          continue
        fi
        case "$file" in
          *.tex)
            stem="${file%.tex}"
            printf '%s/%s\n' "$area" "$stem" >>"$case_specs_file"
            ;;
          *.expected.*)
            stem="${file%%.expected.*}"
            printf '%s/%s\n' "$area" "$stem" >>"$case_specs_file"
            ;;
          *)
            printf '%s\n' "$area" >>"$area_specs_file"
            ;;
        esac
        ;;
    esac
  done < <(incremental_specs)

  if [[ ! -s "$case_specs_file" && ! -s "$area_specs_file" ]]; then
    printf 'No changed fixture sources or expected files found under tests/corpus.\n' >&2
    rm -f "$case_specs_file" "$area_specs_file"
    return
  fi

  while IFS= read -r spec; do
    [[ -n "$spec" ]] || continue
    regen_case "$(case_area_from_arg "$spec")" "$(case_name_from_arg "$spec")"
  done < <(sort -u "$case_specs_file")

  while IFS= read -r area; do
    [[ -n "$area" ]] || continue
    regen_area "$area"
  done < <(sort -u "$area_specs_file")

  rm -f "$case_specs_file" "$area_specs_file"
}

