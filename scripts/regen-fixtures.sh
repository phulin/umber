}

sha256_file() {
  openssl dgst -sha256 -r "$1" | awk '{print $1}'
}

sha512_file() {
  openssl dgst -sha512 -r "$1" | awk '{print $1}'
}

oracle_contract_field() {
  local key="$1"
  awk -v key="$key" '$1 == key { print $2 }' "$oracle_regeneration_manifest"
}

oracle_contract_row() {
  local engine="$1"
  awk -v engine="$engine" '$1 == "engine" && $2 == engine { print }' \
    "$oracle_regeneration_manifest"
}

oracle_fixture_contract_row() {
  local fixture="$1"
  awk -v fixture="$fixture" '$1 == "fixture" && $2 == fixture { print }' \
    "$oracle_regeneration_manifest"
}

# Every registered tex82 command fixture selector, in contract order. This is
# the whole enumeration mechanism: a fixture becomes selectable the moment its
# fixture/fixture-audit rows land in the contract, with no other script or
# registry to update.
tex82_fixture_selectors() {
  awk '$1 == "fixture" && $3 == "tex82" { print $2 }' "$oracle_regeneration_manifest"
}

validate_oracle_source_manifest() {
  local manifest_path="$1"
  local archive_count=0
  local kind url digest extra
  local line_number=0

  [[ -f "$manifest_path" ]] || die "missing oracle source manifest: ${manifest_path}"
  while read -r kind url digest extra; do
    line_number=$((line_number + 1))
    [[ -n "$kind" && "$kind" != \#* ]] || continue
    [[ -z "${extra:-}" ]] ||
      die "${manifest_path}:${line_number}: unexpected manifest field"
    [[ "$kind" == archive ]] ||
      die "${manifest_path}:${line_number}: unknown record kind: ${kind}"
    archive_count=$((archive_count + 1))
    [[ "$url" == https://* ]] ||
      die "${manifest_path}:${line_number}: archive URL must use HTTPS"
    [[ "$digest" =~ ^[0-9a-f]{128}$ ]] ||
      die "${manifest_path}:${line_number}: invalid archive SHA-512"
  done < "$manifest_path"
  [[ "$archive_count" -eq 1 ]] ||
    die "${manifest_path}: expected exactly one archive record"
}

validate_oracle_contract() {
  local selected_engine="$1"
  local bootstrap_fixture="${2:-0}"
  local contract_schema event_schema
  local row_count=0
  local engine profile area manifest_path manifest_digest build_identity extra
  local common_archive=""
  local archive

  [[ -f "$oracle_regeneration_manifest" ]] ||
    die "missing oracle regeneration contract: ${oracle_regeneration_manifest}"
  contract_schema="$(oracle_contract_field contract-schema)"
  event_schema="$(oracle_contract_field event-schema)"
  [[ "$contract_schema" == 2 ]] ||
    die "unsupported oracle regeneration contract schema: ${contract_schema:-missing}"
  [[ "$event_schema" == 1 ]] ||
    die "unsupported oracle event schema: ${event_schema:-missing}"
  [[ "$(awk '$1 == "contract-schema" { count++ } END { print count + 0 }' \
      "$oracle_regeneration_manifest")" -eq 1 ]] ||
    die 'oracle regeneration contract must declare contract-schema exactly once'
  [[ "$(awk '$1 == "event-schema" { count++ } END { print count + 0 }' \
      "$oracle_regeneration_manifest")" -eq 1 ]] ||
    die 'oracle regeneration contract must declare event-schema exactly once'
  awk '
    /^[[:space:]]*($|#)/ { next }
    $1 == "contract-schema" || $1 == "event-schema" ||
      $1 == "engine" || $1 == "fixture" || $1 == "fixture-audit" { next }
    { print FILENAME ":" FNR ": unknown contract record: " $1 > "/dev/stderr"; exit 1 }
  ' "$oracle_regeneration_manifest" ||
    die 'oracle regeneration contract contains an unknown record'
  for engine in tex82 etex26 pdftex14027; do
    [[ "$(awk -v engine="$engine" \
      '$1 == "engine" && $2 == engine { count++ } END { print count + 0 }' \
      "$oracle_regeneration_manifest")" -eq 1 ]] ||
      die "oracle regeneration contract must declare ${engine} exactly once"
  done

  while read -r _ engine profile area manifest_path manifest_digest \
    build_identity extra; do
    [[ -n "$engine" ]] || continue
    [[ -z "${extra:-}" ]] || die "unexpected field in ${engine} contract row"
    row_count=$((row_count + 1))
    case "${engine}:${profile}:${area}:${build_identity}" in
      tex82:initex-eight-bit:tex82-oracle:tex82-oracle-web2c-texlive-2025 | \
      etex26:compatibility+extended-eight-bit:etex26-oracle:etex26-oracle-web2c-texlive-2025 | \
      pdftex14027:initex-etex-eight-bit:pdftex14027-oracle:pdftex14027-oracle-web2c-texlive-2025)
        ;;
      *)
        die "unsupported oracle identity/profile contract: ${engine}:${profile}"
        ;;
    esac
    [[ -f "$manifest_path" ]] || die "missing ${engine} manifest: ${manifest_path}"
    local generated_manifest_digest
    generated_manifest_digest="$(sha256_file "$manifest_path")"
    [[ "$generated_manifest_digest" == "$manifest_digest" ]] ||
      die "${engine} source manifest identity drift: ${manifest_path}: expected ${manifest_digest}, generated ${generated_manifest_digest}"
    if [[ "$selected_engine" == all || "$selected_engine" == "$engine" ]]; then
      validate_oracle_source_manifest "$manifest_path"
    fi
    archive="$(awk '$1 == "archive" { print $2 " " $3 }' "$manifest_path")"
    if [[ -z "$common_archive" ]]; then
      common_archive="$archive"
    else
      [[ "$archive" == "$common_archive" ]] ||
        die "oracle source manifests do not pin the same immutable archive"
    fi
  done < <(awk '$1 == "engine" { print }' "$oracle_regeneration_manifest")
  [[ "$row_count" -eq 3 ]] ||
    die "oracle regeneration contract must contain exactly three engines"

  # Every committed tex82 command fixture is validated the same way,
  # generically: this loop is the whole selector list, so registering another
  # split fixture needs only a fixture/fixture-audit pair in the contract, not
  # a code change here. `$3` (the fixture currently being bootstrapped, if
  # any) is the one committed manifest allowed to disagree with the contract's
  # pinned digest, because bootstrapping is what is about to update it.
  local bootstrap_selector="${3:-}"
  local fixture_count=0
  local fixture_selector fixture_engine fixture_profile
  local fixture_manifest fixture_manifest_digest fixture_extra
  while read -r _ fixture_selector fixture_engine fixture_profile fixture_manifest \
    fixture_manifest_digest fixture_extra; do
    [[ -n "$fixture_selector" ]] || continue
    fixture_count=$((fixture_count + 1))
    [[ -z "${fixture_extra:-}" &&
        "$fixture_engine" == tex82 &&
        "$fixture_profile" == initex-eight-bit ]] ||
      die "${fixture_selector} has a noncanonical TeX82 fixture regeneration identity"
    [[ "$fixture_manifest" == "$(tex82_fixture_directory "$fixture_selector")/manifest.json" ]] ||
      die "${fixture_selector} pins manifest ${fixture_manifest} instead of $(tex82_fixture_directory "$fixture_selector")/manifest.json"
    if [[ "$bootstrap_fixture" -eq 0 || "$fixture_selector" != "$bootstrap_selector" ]]; then
      [[ -f "$fixture_manifest" &&
          "$(sha256_file "$fixture_manifest")" == "$fixture_manifest_digest" ]] ||
        die "${fixture_selector} committed fixture manifest identity drift"
    fi
    local audit_record audit_selector semantic_matrix semantic_digest
    local audit_matrix audit_digest audit_extra
    audit_record="$(tex82_fixture_matrix_row "$fixture_selector")"
    [[ -n "$audit_record" ]] || die "${fixture_selector} has no fixture-audit contract row"
    read -r _ audit_selector semantic_matrix semantic_digest audit_matrix \
      audit_digest audit_extra <<<"$audit_record"
    [[ -z "${audit_extra:-}" &&
        -f "$semantic_matrix" &&
        -f "$audit_matrix" &&
        "$(sha256_file "$semantic_matrix")" == "$semantic_digest" &&
        "$(sha256_file "$audit_matrix")" == "$audit_digest" ]] ||
      die "${fixture_selector} fixture audit identity drift"
  done < <(awk '$1 == "fixture" { print }' "$oracle_regeneration_manifest")
  [[ "$fixture_count" -ge 1 ]] ||
    die 'oracle regeneration contract must declare at least one TeX82 command fixture'
  local audit_row_count
  audit_row_count="$(awk '$1 == "fixture-audit" { count++ } END { print count + 0 }' \
    "$oracle_regeneration_manifest")"
  [[ "$audit_row_count" -eq "$fixture_count" ]] ||
    die 'oracle regeneration contract has a fixture-audit row with no matching fixture'
  [[ -n "$(oracle_contract_row "$selected_engine")" || "$selected_engine" == all ]] ||
    die "unknown oracle engine: ${selected_engine}"
}

validate_oracle_build_record() {
  local engine="$1"
  local row profile area manifest_path manifest_digest build_identity
  local record trace_count=0 trace
  row="$(oracle_contract_row "$engine")"
  read -r _ _ profile area manifest_path manifest_digest build_identity <<<"$row"
  record="${target_dir}/${area}/build-record.txt"
  [[ -f "$record" ]] || die "${engine} build did not write ${record}"
  grep -Fqx "identity ${build_identity}" "$record" ||
    die "${engine} build identity drift"
  grep -Fqx "manifest-sha256 ${manifest_digest}" "$record" ||
    die "${engine} build record does not bind the pinned source manifest"
  case "$engine" in
    tex82)
      grep -Fqx 'engine TeX' "$record" &&
        grep -Fqx 'engine-version 3.141592653' "$record" &&
        grep -Fqx 'character-profile eight-bit-exact' "$record" &&
        grep -Fqx 'invocation-profile INITEX' "$record" ||
        die 'TeX82 build profile identity drift'
      ;;
    etex26)
      grep -Fqx 'engine e-TeX' "$record" &&
        grep -Fqx 'engine-version 2.6' "$record" &&
        grep -Fqx 'character-profile eight-bit-exact' "$record" &&
        grep -Fqx 'profile compatibility invocation-input smoke.tex' "$record" &&
        grep -Fqx 'profile extended invocation-input *smoke.tex' "$record" ||
        die 'e-TeX build profile identity drift'
      ;;
    pdftex14027)
      grep -Fqx 'engine pdfTeX' "$record" &&
        grep -Fqx 'engine-version 1.40.27' "$record" &&
        grep -Fqx 'etex-version 2.6' "$record" &&
        grep -Fqx 'character-profile eight-bit-exact' "$record" &&
        grep -Fqx 'invocation-profile INITEX-with-etex-extensions' "$record" ||
        die 'pdfTeX build profile identity drift'
      ;;
  esac
  while IFS= read -r trace; do
    trace_count=$((trace_count + 1))
    if [[ "$engine" == tex82 && "$trace" == */geometry/* ]]; then
      [[ "$(sed -n '1p' "$trace")" == '{"schema":2,'* ]] ||
        die "${engine} geometry profile emitted a trace without a schema-v2 header"
    else
      [[ "$(sed -n '1p' "$trace")" == '{"schema":1,'* ]] ||
        die "${engine} emitted a trace without a schema-v1 header"
    fi
    cargo run -q -p tex-oracle --bin tex-oracle-validate -- "$trace" ||
      die "${engine} emitted an invalid semantic trace"
  done < <(find "${target_dir}/${area}" -type f -name '*events.jsonl' | sort)
  [[ "$trace_count" -gt 0 ]] || die "${engine} build emitted no semantic traces"
}

tex82_fixture_directory() {
  printf 'tests/corpus/command/%s\n' "$1"
}

tex82_fixture_matrix_row() {
  local fixture="$1"
  awk -v selector="$fixture" '$1 == "fixture-audit" && $2 == selector { print; exit }' \
    "$oracle_regeneration_manifest"
}

validate_committed_oracle_fixture() {
  local fixture="$1"
  local compare_live="${2:-0}"
  local fixture_dir
  local live_dir
  local candidate_events
  local expected_header
  local source channel_path channel semantic_matrix audit_matrix
  local audit_record audit_selector semantic_digest audit_digest audit_extra

  [[ -n "$(oracle_fixture_contract_row "$fixture")" ]] ||
    die "unknown committed oracle fixture: ${fixture}"
  fixture_dir="${repo_root}/$(tex82_fixture_directory "$fixture")"
  live_dir="${target_dir}/tex82-oracle/${fixture#tex82/}/clean"
  audit_record="$(tex82_fixture_matrix_row "$fixture")"
  [[ -n "$audit_record" ]] || die "${fixture} has no fixture-audit contract row"
  read -r _ audit_selector semantic_matrix semantic_digest audit_matrix \
    audit_digest audit_extra <<<"$audit_record"

  run_command "Validating committed oracle fixture ${fixture}" \
    cargo run -q -p tex-oracle --bin tex-oracle-validate -- \
      --fixture "$fixture_dir" \
      --semantic-matrix "$semantic_matrix" \
      --audit-matrix "$audit_matrix"

  [[ "$compare_live" -eq 1 ]] || return 0
  for source in "${fixture_dir}"/sources/*; do
    cmp -s "$source" "${live_dir}/$(basename "$source")" ||
      die "${fixture} focused source drift: $(basename "$source")"
  done
  for channel_path in "${fixture_dir}"/outputs/*; do
    channel="$(basename "$channel_path")"
    cmp -s "$channel_path" "${live_dir}/${channel}" ||
      die "${fixture} ${channel} observation drift"
  done

  candidate_events="$(mktemp)"
  expected_header="$(sed -n '1p' "${fixture_dir}/events.jsonl")"
  {
    printf '%s\n' "$expected_header"
    sed -n '2,$p' \
      "${target_dir}/tex82-oracle/${fixture#tex82/}/instrumentable/tex82-events.jsonl"
  } >"$candidate_events"
  cmp -s "${fixture_dir}/events.jsonl" "$candidate_events" || {
    rm -f "$candidate_events"
    die "${fixture} normalized semantic event stream drift"
  }
  rm -f "$candidate_events"
}

bootstrap_tex82_oracle_fixture() {
  local fixture="$1"
  local fixture_dir
  fixture_dir="${repo_root}/$(tex82_fixture_directory "$fixture")"
  local fixture_parent fixture_name candidate_dir backup_dir
  local contract_candidate manifest_digest
  local audit_record audit_selector semantic_matrix semantic_digest audit_matrix
  local audit_digest audit_extra
  audit_record="$(tex82_fixture_matrix_row "$fixture")"
  [[ -n "$audit_record" ]] || die "${fixture} has no fixture-audit contract row"
  read -r _ audit_selector semantic_matrix semantic_digest audit_matrix \
    audit_digest audit_extra <<<"$audit_record"
  fixture_parent="$(dirname "$fixture_dir")"
  fixture_name="$(basename "$fixture_dir")"
  candidate_dir="$(mktemp -d "${fixture_parent}/.${fixture_name}.bootstrap.XXXXXX")"
  contract_candidate="$(mktemp "${repo_root}/tests/.oracle-regeneration-manifest.XXXXXX")"

  run_command "Deriving ${fixture} candidate from pinned TeX82 oracle" \
    cargo run -q -p tex-oracle --bin tex-oracle-bootstrap -- \
      --template "$fixture_dir" \
      --live-directory "${target_dir}/tex82-oracle/${fixture#tex82/}/clean" \
      --semantic-matrix "$semantic_matrix" \
      --event-stream "${target_dir}/tex82-oracle/${fixture#tex82/}/instrumentable/tex82-events.jsonl" \
      --build-record "${target_dir}/tex82-oracle/build-record.txt" \
      --output "$candidate_dir"
  run_command "Validating derived ${fixture} candidate (including the minifixture budget)" \
    cargo run -q -p tex-oracle --bin tex-oracle-validate -- \
      --fixture "$candidate_dir" \
      --semantic-matrix "$semantic_matrix" \
      --audit-matrix "$audit_matrix"

  manifest_digest="$(sha256_file "${candidate_dir}/manifest.json")"
  awk -v selector="$fixture" -v digest="$manifest_digest" '
    $1 == "fixture" && $2 == selector { $6 = digest }
    { print }
  ' "$oracle_regeneration_manifest" >"$contract_candidate"
  [[ "$(awk -v selector="$fixture" -v digest="$manifest_digest" \
      '$1 == "fixture" && $2 == selector && $6 == digest { count++ } END { print count + 0 }' \
      "$contract_candidate")" -eq 1 ]] ||
    die 'derived fixture contract does not bind the candidate manifest'

  backup_dir="${fixture_parent}/.${fixture_name}.pre-bootstrap.$$"
  [[ ! -e "$backup_dir" ]] || die "bootstrap backup path exists: ${backup_dir}"
  mv "$fixture_dir" "$backup_dir"
  if ! mv "$candidate_dir" "$fixture_dir"; then
    mv "$backup_dir" "$fixture_dir"
    rm -f "$contract_candidate"
    die 'failed to publish derived fixture candidate'
  fi
  if ! mv "$contract_candidate" "$oracle_regeneration_manifest"; then
    mv "$fixture_dir" "$candidate_dir"
    mv "$backup_dir" "$fixture_dir"
    rm -rf "$candidate_dir"
    die 'failed to publish derived fixture contract'
  fi
  rm -rf "$backup_dir"
  run_command "Validating published ${fixture} suite" \
    cargo run -q -p tex-oracle --bin tex-oracle-validate -- --tex82-command-suite
}

write_cross_engine_oracle_record() {
  local output_dir="${target_dir}/oracle-regeneration"
  local engine row profile area manifest_path manifest_digest build_identity
  mkdir -p "$output_dir"
  {
    printf 'contract-schema 2\n'
    printf 'event-schema 1\n'
    printf 'contract-sha256 %s\n' "$(sha256_file "$oracle_regeneration_manifest")"
    for engine in tex82 etex26 pdftex14027; do
      row="$(oracle_contract_row "$engine")"
      read -r _ _ profile area manifest_path manifest_digest build_identity <<<"$row"
      printf 'engine %s %s %s %s\n' \
        "$engine" "$profile" "$manifest_digest" \
        "$(sha256_file "${target_dir}/${area}/build-record.txt")"
    done
    printf 'transparency clean-instrumented-pass\n'
  } >"${output_dir}/build-record.txt"
}

regen_oracle() {
  local engine="$1"
  local profile="$2"
  local offline="$3"
  local validate_only="$4"
  local fixture="${5:-}"
  local bootstrap_fixture="${6:-0}"
  local expected_profile
  local area
  local selected_engines
  local builder_args=()

  case "$engine" in
    tex82) expected_profile=initex-eight-bit ;;
    etex26) expected_profile=compatibility+extended-eight-bit ;;
    pdftex14027) expected_profile=initex-etex-eight-bit ;;
    all) expected_profile=canonical ;;
    *) die "unknown oracle engine: ${engine}" ;;
  esac
  [[ "$profile" == "$expected_profile" ]] ||
    die "oracle ${engine} requires --profile ${expected_profile}"
  if [[ -n "$fixture" ]]; then
    [[ "$engine" == tex82 && "$profile" == initex-eight-bit ]] ||
      die "fixture ${fixture} requires --oracle tex82 --profile initex-eight-bit"
    [[ -n "$(oracle_fixture_contract_row "$fixture")" ]] ||
      die "unknown committed oracle fixture: ${fixture}"
  fi
  [[ "$bootstrap_fixture" -eq 0 || "$validate_only" -eq 0 ]] ||
    die '--bootstrap-fixture cannot be combined with --validate-only'
  [[ "$bootstrap_fixture" -eq 0 || -n "$fixture" ]] ||
    die '--bootstrap-fixture requires an explicit --fixture selector'
  validate_oracle_contract "$engine" "$bootstrap_fixture" "$fixture"
  if [[ "$validate_only" -eq 1 ]]; then
    if [[ -n "$fixture" ]]; then
      validate_committed_oracle_fixture "$fixture" 0
    elif [[ "$engine" == tex82 || "$engine" == all ]]; then
      local selector
      for selector in $(tex82_fixture_selectors); do
        validate_committed_oracle_fixture "$selector" 0
      done
    fi
    return 0
  fi
  [[ "$offline" -eq 0 ]] || builder_args+=(--offline)

  if [[ "$engine" == all ]]; then
    selected_engines=(tex82 etex26 pdftex14027)
  else
    selected_engines=("$engine")
  fi
  for engine in "${selected_engines[@]}"; do
    case "$engine" in
      tex82) area="$tex82_oracle_area" ;;
      etex26) area="$etex26_oracle_area" ;;
      pdftex14027) area="$pdftex14027_oracle_area" ;;
    esac
    run_command "Running ${engine} canonical transparency workflow" \
      "${repo_root}/scripts/build-${area}.sh" "${builder_args[@]}"
    validate_oracle_build_record "$engine"
  done
  if [[ "$bootstrap_fixture" -eq 1 ]]; then
    bootstrap_tex82_oracle_fixture "$fixture"
  elif [[ -n "$fixture" ]]; then
    validate_committed_oracle_fixture "$fixture" 1
  elif [[ "$profile" == canonical || "$engine" == tex82 ]]; then
    local selector
    for selector in $(tex82_fixture_selectors); do
      validate_committed_oracle_fixture "$selector" 1
    done
  fi
  if [[ "$profile" == canonical ]]; then
    write_cross_engine_oracle_record
  fi
}

regen_bib_area() {
  local upstream="${UMBER_REF_BIBER_SOURCE:-}"
  local fixture_dir="${repo_root}/tests/corpus/bib/upstream-2.22"
  local staged_dir
  local manifest
  local file
  local relative
  local upstream_path
  local separator=""
  local bytes
  local digest

  [[ -n "$upstream" && -d "$upstream/.git" ]] || \
    die 'set UMBER_REF_BIBER_SOURCE to a local clone of the upstream repository'
  git -C "$upstream" cat-file -e "${bib_upstream_commit}^{commit}" 2>/dev/null || \
    die "upstream clone does not contain commit ${bib_upstream_commit}"
  command -v openssl >/dev/null || die 'openssl is required to hash bibliography fixtures'

  staged_dir="$(mktemp -d)"
  git -C "$upstream" archive "$bib_upstream_commit" LICENSE t/tdata | tar -x -C "$staged_dir"
  mkdir -p "$staged_dir/tdata"
  mv "$staged_dir/LICENSE" "$staged_dir/LICENSE.Artistic-2.0"
  mv "$staged_dir/t/tdata"/* "$staged_dir/tdata/"
  rmdir "$staged_dir/t/tdata" "$staged_dir/t"

  manifest="$staged_dir/manifest.json"
  {
    printf '%s\n' '{'
    printf '%s\n' '  "schema": 1,'
    printf '%s\n' '  "upstream_repository": "https://github.com/plk/biber.git",'
    printf '  "upstream_commit": "%s",\n' "$bib_upstream_commit"
    printf '%s\n' '  "compatibility_version": "2.22 beta",'
    printf '%s\n' '  "license": "Artistic-2.0",'
    printf '%s\n' '  "files": ['
    while IFS= read -r file; do
      relative="${file#"$staged_dir"/}"
      [[ "$relative" != "manifest.json" ]] || continue
      if [[ "$relative" == "LICENSE.Artistic-2.0" ]]; then
        upstream_path="LICENSE"
      else
        upstream_path="t/${relative}"
      fi
      bytes="$(wc -c < "$file" | tr -d ' ')"
      digest="$(sha256_file "$file")"
      printf '%s' "$separator"
      printf '%s\n' '    {'
      printf '      "path": "%s",\n' "$relative"
      printf '      "upstream_path": "%s",\n' "$upstream_path"
      printf '      "bytes": %s,\n' "$bytes"
      printf '      "sha256": "%s"\n' "$digest"
      printf '%s' '    }'
      separator=$',\n'
    done < <(find "$staged_dir" -type f | LC_ALL=C sort)
    printf '\n%s\n' '  ]'
    printf '%s\n' '}'
  } > "$manifest"

  rm -rf "$fixture_dir"
  mkdir -p "$(dirname "$fixture_dir")"
  mv "$staged_dir" "$fixture_dir"
  run_command 'Validating pinned bibliography fixtures' \
    cargo test -p bib-engine --test it fixture_manifest_is_complete_and_pinned
}

