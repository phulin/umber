    --oracle)
      [[ -z "$mode" || "$mode" == oracle ]] || die "choose exactly one mode"
      [[ "$#" -ge 2 ]] || die "missing engine after --oracle"
      mode="oracle"
      oracle_engine="$2"
      shift 2
      ;;
    --profile)
      [[ "$#" -ge 2 ]] || die "missing profile after --profile"
      if [[ "$mode" == oracle ]]; then
        oracle_profile="$2"
      elif [[ "$mode" == area && "$area_arg" == "$command_semantic_area" ]]; then
        command_semantic_profile="$2"
      else
        die "--profile requires --oracle or --area command-semantic"
      fi
      shift 2
      ;;
    --allowlist)
      [[ "$mode" == area && "$area_arg" == "$command_semantic_area" ]] ||
        die "--allowlist requires --area command-semantic"
      [[ "$#" -ge 2 ]] || die "missing file after --allowlist"
      command_semantic_allowlist="$2"
      shift 2
      ;;
    --offline)
      [[ "$mode" == oracle ]] || die "--offline requires --oracle"
      oracle_offline=1
      shift
      ;;
    --fixture)
      [[ "$mode" == oracle ]] || die "--fixture requires --oracle"
      [[ "$#" -ge 2 ]] || die "missing fixture after --fixture"
      oracle_fixture="$2"
      shift 2
      ;;
    --validate-only)
      [[ "$mode" == oracle ]] || die "--validate-only requires --oracle"
      oracle_validate_only=1
      shift
      ;;
    --bootstrap-fixture)
      [[ "$mode" == oracle ]] || die "--bootstrap-fixture requires --oracle"
      oracle_bootstrap_fixture=1
      shift
      ;;
    *)
      die "unknown argument: $1"
      ;;
  esac
done

case "$mode" in
  incremental)
    regen_incremental
    ;;
  all)
    for area_arg in "${text_areas[@]}"; do
      regen_area "$area_arg"
    done
    for area_arg in "${dvi_areas[@]}"; do
      regen_area "$area_arg"
    done
    regen_area "$pdf_area"
    regen_area "$e2e_area"
    regen_area "$bib_area"
    regen_area "$bibtex_area"
    regen_oracle all canonical 0 0
    ;;
  area)
    regen_area "$area_arg"
    ;;
  case)
    [[ -n "$case_area" && -n "$case_name" ]] || die "missing case"
    regen_case "$case_area" "$case_name"
    ;;
  oracle)
    [[ -n "$oracle_engine" ]] || die "missing oracle engine"
    [[ -n "$oracle_profile" ]] || die "--oracle requires --profile"
    regen_oracle "$oracle_engine" "$oracle_profile" \
      "$oracle_offline" "$oracle_validate_only" "$oracle_fixture" \
      "$oracle_bootstrap_fixture"
    ;;
  *)
    usage
    exit 2
    ;;
esac

# `--validate-only` promises to leave the working tree alone, so it is the one
# mode that must not format; every other mode has just written fixtures.
if [[ "$mode" != oracle || "$oracle_validate_only" -eq 0 ]]; then
  format_regenerated_output
fi
